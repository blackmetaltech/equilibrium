#!/usr/bin/env python3
"""Port Henry constants, steam points, BFW enthalpy, API 520/526 data and the NRTL binary pairs into src/data/vle.gen.ts.
Run (repo root):  python3 -I scripts/port-vle.py
Reads docs/research/vle_safety.md and docs/research/vle_binary.py (NRTL A12, A21, alpha; parsed by regex, nothing retyped). Antoine rows live on the species catalogue."""
import json, os, re, sys
sys.dont_write_bytecode = True
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
md = open(os.path.join(ROOT, 'docs', 'research', 'vle_safety.md'), encoding='utf-8').read()

def section(title_start):
    i = md.index(title_start); j = md.find('\n## ', i + 5)
    return md[i:j if j > 0 else len(md)]

def rows(text, ncol):
    out = []
    for ln in text.splitlines():
        if ln.startswith('|') and not re.match(r'^\|[-| ]+\|$', ln):
            c = [x.strip() for x in ln.strip().strip('|').split('|')]
            if len(c) >= ncol: out.append(c)
    return out

# Henry (sec 3): Hcp at 298.15 K mol/(m3 Pa), d ln H / d(1/T) K
henry = {}
for c in rows(section("## 3. Henry"), 3)[1:]:
    henry[c[0]] = {'Hcp': float(c[1]), 'C': float(re.match(r'[\d.]+', c[2]).group())}
# steam (sec 4)
s4 = section("## 4. Steam")
steam = {}
for c in rows(s4, 5)[1:]:
    steam[int(c[0])] = {'Tsat_C': float(c[1]), 'hf': float(c[2]), 'hg': float(c[3]), 'hfg': float(c[4])}
bfw = float(re.search(r'105 C: h = ([\d.]+) kJ/kg', s4).group(1))
# API (sec 5)
s5 = section("## 5. API 520")
orifice = {}
for c in rows(s5, 3):
    if re.fullmatch(r'[A-Z]', c[0]): orifice[c[0]] = {'in2': float(c[1]), 'mm2': float(c[2])}
cc = float(re.search(r'C = ([\d.]+) \* sqrt', s5).group(1))
kd = float(re.search(r'K_d = ([\d.]+)', s5).group(1))
assert len(henry) == 9 and set(steam) == {4, 10, 40} and len(orifice) == 14, (len(henry), steam, len(orifice))
# NRTL pairs (docs/research/vle_binary.py): A in cal/mol, tau = A/(R T); component ids are the catalogue gas ids
vb = open(os.path.join(ROOT, 'docs', 'research', 'vle_binary.py'), encoding='utf-8').read()
R_cal = float(re.search(r'^R=([\d.]+)', vb, re.M).group(1))
nrtl = {}
for key, pat in (('C2H5OH|H2O', r"'EtOH-H2O NRTL[^']*':\('eth','wat',lambda x,T:nrtl\(x,T,([-\d.]+),([-\d.]+),([\d.]+)\)"),
                 ('CH3OH|H2O', r"'MeOH-H2O NRTL[^']*':\('met','wat',lambda x,T:nrtl\(x,T,([-\d.]+),([-\d.]+),([\d.]+)\)")):
    m = re.search(pat, vb)
    nrtl[key] = {'A12': float(m.group(1)), 'A21': float(m.group(2)), 'alpha': float(m.group(3))}
# NH3-air flammability vs T (sec 6, Harris & MacDermott / ICI) and the BREF NO-yield bands vs pressure (sec 7, Table 3.2): parsed from the sentences, not retyped
s6 = section("## 6. Flammability")
m6 = re.search(r'([\d.]+)-([\d.]+) % at ambient; ([\d.]+)-([\d.]+) % at (\d+) C; ([\d.]+)-([\d.]+) % at (\d+) C', s6)
flamm = [{'T_C': 20.0, 'lfl': float(m6.group(1)), 'ufl': float(m6.group(2))}, {'T_C': float(m6.group(5)), 'lfl': float(m6.group(3)), 'ufl': float(m6.group(4))},
         {'T_C': float(m6.group(8)), 'lfl': float(m6.group(6)), 'ufl': float(m6.group(7))}]
s7 = section("## 7. Ostwald")
m7 = re.search(r'<([\d.]+) bar, (\d+)-(\d+) C: (\d+) %; ([\d.]+)-([\d.]+) bar, (\d+)-(\d+) C: (\d+) %; >([\d.]+) bar, (\d+)-(\d+) C: (\d+) %', s7)
g = [float(x) for x in m7.groups()]
ostwald = [{'Pmax_bar': g[0], 'Tlo_C': g[1], 'Thi_C': g[2], 'S_NO': g[3] / 100}, {'Pmax_bar': g[5], 'Tlo_C': g[6], 'Thi_C': g[7], 'S_NO': g[8] / 100},
           {'Pmax_bar': 1e9, 'Tlo_C': g[10], 'Thi_C': g[11], 'S_NO': g[12] / 100}]
j = lambda x: json.dumps(x, indent=2)
out = f"""// GENERATED by scripts/port-vle.py (python3 -I scripts/port-vle.py). DO NOT EDIT BY HAND.
// Source: docs/research/vle_binary.py (NRTL), docs/research/vle_safety.md sec 3 (Sander Henry, FETCHED), sec 4 (steam, CoolProp IF97, DERIVED), sec 5 (API 520/526, F2).
export const HENRY_GEN = {j(henry)};
export const STEAM_GEN = {j(steam)};
export const BFW_H_GEN = {bfw};
// NH3-air flammable envelope vs temperature (ICI, sec 6) and NO yield bands vs pressure (BREF Table 3.2, sec 7)
export const FLAMM_NH3_GEN = {j(flamm)};
export const OSTWALD_BANDS_GEN = {j(ostwald)};
// NRTL, ChemSep/DECHEMA at 1 atm via docs/research/vle_binary.py: tau_ij = A_ij / (R T), A in cal/mol, R in cal/(mol K)
export const NRTL_R_GEN = {R_cal};
export const NRTL_GEN = {j(nrtl)};
export const API_GEN = {{ C0: {cc}, Kd: {kd}, orifice: {j(orifice)} }};
"""
open(os.path.join(ROOT, 'src', 'data', 'vle.gen.ts'), 'w').write(out)
print('ok', len(henry), steam, bfw, cc, kd)
